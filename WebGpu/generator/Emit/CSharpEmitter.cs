	/// <summary>
	/// Writes the raw binding as C# source. Everything emitted here is 1:1 with the C API - same type
	/// names, same member names, same order - so that a reader can hold webgpu.h beside it. Ergonomics
	/// belong in a separate hand written layer, never in these files.
	/// </summary>
	public sealed class CSharpEmitter
	{
		private const string Namespace = "MatterHackers.WebGpu";
		private const int MaxFileLines = 800;

		private readonly ApiModel model;
		private readonly string outputDirectory;
		private readonly string version;

		public CSharpEmitter(ApiModel model, string outputDirectory, string version)
		{
			this.model = model;
			this.outputDirectory = outputDirectory;
			this.version = version;
		}

		public List<string> WrittenFiles { get; } = new List<string>();

		public void EmitAll()
		{
			Directory.CreateDirectory(this.outputDirectory);
			this.EmitCoreTypes();
			this.EmitEnums();
			this.EmitHandles();
			this.EmitStructs();
			this.EmitFunctions();
			this.EmitStructLayouts();
			this.EmitWasm32StructLayouts();
		}

