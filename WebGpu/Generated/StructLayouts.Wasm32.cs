			Check(mismatches, "WGPUWaylandDisplayHandle", Unsafe.SizeOf<WGPUWaylandDisplayHandle>(), 4);
			Check(mismatches, "WGPUXcbDisplayHandle", Unsafe.SizeOf<WGPUXcbDisplayHandle>(), 8);
			Check(mismatches, "WGPUXlibDisplayHandle", Unsafe.SizeOf<WGPUXlibDisplayHandle>(), 8);

			return mismatches.Count == 0 ? null : string.Join("; ", mismatches);
		}

		private static void Check(List<string> mismatches, string name, int actual, int expected)
		{
			if (actual != expected)
			{
				mismatches.Add($"{name}: this build says {actual} bytes, wasm32 C says {expected}");
			}
		}
